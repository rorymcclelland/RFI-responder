/**
 * Sprint 14 (S14-2): the demo data for a hosted project. The local seed (supabase/seed.sql) creates the
 * fictional people with a shared development password, which must never reach a hosted project
 * (docs/DEPLOYING.md). This builds the same knowledge base and demo responses, from the same generated
 * sections of the seed, with the fictional people as authors who cannot sign in: no password, no email
 * identity, banned, and at `@example.invalid` addresses, which can never receive mail.
 */
export interface DemoUser { email: string; display_name: string; job_title: string; department: string; tags: string[] }

const SECTIONS = ['KNOWLEDGE BASE', 'DEMO RESPONSES'] as const;
/** Every table the demo data fills; truncating these two cascades to responses, sessions, questions, approvals, assignments and contributors. */
const RESET_TABLES = ['public.opportunities', 'public.kb_entries'];

/** The fictional people, from the seed's own list. */
export function demoUsersFromSeed(seed: string): DemoUser[] {
  const m = seed.match(/users_data jsonb := '(\[[\s\S]*?\])';/);
  if (!m) throw new Error('supabase/seed.sql has no users_data list');
  return JSON.parse(m[1]) as DemoUser[];
}

function section(seed: string, name: string): string {
  const begin = `-- BEGIN ${name} (generated by npm run demo:seed; do not edit by hand)`;
  const i = seed.indexOf(begin);
  const j = seed.indexOf(`-- END ${name}`, i);
  if (i < 0 || j < 0) throw new Error(`supabase/seed.sql has no "${name}" section`);
  return seed.slice(i + begin.length, j).trim();
}

/** example.com (a real, reserved domain) becomes example.invalid (which can never resolve). */
const invalid = (s: string) => s.replace(/@example\.com\b/g, '@example.invalid');

function usersSql(users: DemoUser[]): string {
  const data = JSON.stringify(users.map((u) => ({ ...u, email: invalid(u.email) })), null, 2).replace(/'/g, "''");
  return `-- The fictional people: authors of the demo data only. No password, no email identity, banned until
-- 2999, at addresses that can never receive mail: nobody can sign in as them.
DO $users$
DECLARE
  uid uuid;
  u jsonb;
  users_data jsonb := '${data}';
BEGIN
  FOR u IN SELECT * FROM jsonb_array_elements(users_data)
  LOOP
    SELECT id INTO uid FROM auth.users WHERE email = u->>'email';
    IF uid IS NULL THEN
      uid := gen_random_uuid();
      INSERT INTO auth.users (
        instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, banned_until,
        raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
        confirmation_token, recovery_token, email_change_token_new, email_change
      ) VALUES (
        '00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated',
        u->>'email', '', NULL, '2999-12-31',
        '{"provider":"email","providers":["email"]}',
        jsonb_build_object('display_name', u->>'display_name'), now(), now(),
        '', '', '', ''
      );
    END IF;
    UPDATE public.user_profiles SET
      display_name   = u->>'display_name',
      job_title      = u->>'job_title',
      department     = u->>'department',
      expertise_tags = ARRAY(SELECT jsonb_array_elements_text(u->'tags')),
      is_admin       = (u->>'email' = 'sarah.chen@example.invalid')
    WHERE id = uid;
  END LOOP;
END $users$;`;
}

const HEADER = `-- Demo data for a hosted RFI Respond (generated by npm run demo:hosted from supabase/seed.sql; do not edit
-- by hand). Synthetic only. Run it in the hosted project's SQL editor, as the project owner. Safe to run
-- twice: each part is skipped if its data is already there.`;

/** The load: the fictional people, then the knowledge base and the demo responses. */
export function hostedDemoSql(seed: string): string {
  const parts = SECTIONS.map((s) => invalid(section(seed, s)));
  const out = [HEADER, '', usersSql(demoUsersFromSeed(seed)), '', ...parts, ''].join('\n');
  check(out);
  return out;
}

/** The reset: removes every response and knowledge-base entry (the reviewers' too), then loads the demo again. Accounts, roles, settings, usage and the audit log are kept. */
export function hostedResetSql(seed: string): string {
  const load = hostedDemoSql(seed).replace(HEADER, '').trim();
  return [`-- Reset the hosted demo (generated by npm run demo:hosted; do not edit by hand). Removes every response
-- and knowledge-base entry, including what reviewers added, then loads the demo data again. Real accounts,
-- their roles, the settings, usage and the audit log are kept. Run it in the SQL editor, as the project owner.`,
  'BEGIN;', `TRUNCATE ${RESET_TABLES.join(', ')} CASCADE;`, load, 'COMMIT;', ''].join('\n');
}

/** Refuses anything that would let someone sign in as a fictional person. */
export function check(sql: string): void {
  if (/LocalDev|crypt\(|gen_salt\(/.test(sql)) throw new Error('The hosted demo data must not set a password');
  if (/@example\.com\b/.test(sql)) throw new Error('The hosted demo data must not use @example.com addresses');
  if (/auth\.identities/.test(sql)) throw new Error('The hosted demo data must not create sign-in identities');
}
