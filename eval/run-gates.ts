/**
 * Gate evaluation for Sprint 2 (story S2-3). Run on Rory's PC:
 *
 *   npm run eval:gates
 *
 * Runs the rules and the Claude classifier over eval/gate-set.json and reports, for the rules
 * alone and for the combination the app uses (gated if either fires): how many pricing and legal
 * questions are gated (bar: all of them) and how many lookalikes are wrongly gated (bar: at most
 * 15%). The rules were written while looking at the "tuning" split; the "holdout" split was
 * written afterwards and is the honest estimate. Classifier answers are cached.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { claudeClient } from '../supabase/functions/_shared/claude';
import { classifierGate, GATE_PROMPT_VERSION, ruleGate } from '../supabase/functions/_shared/gates';
import { diskCache, env, ROOT, withRetry } from './lib';

const MODEL = 'claude-haiku-5-5';
const BARS = { recall: 1, falsePositive: 0.15 };

interface Item { id: string; text: string; language: string; category: 'pricing' | 'legal' | 'none'; split: string }
const set = JSON.parse(readFileSync(join(ROOT, 'eval/gate-set.json'), 'utf8')) as { version: string; items: Item[] };

async function main() {
  if (!env.ANTHROPIC_API_KEY) {
    console.error('ANTHROPIC_API_KEY is not set in supabase/functions/.env');
    process.exit(1);
  }
  const client = claudeClient({ apiKey: env.ANTHROPIC_API_KEY, retry: { attempts: 10, baseDelayMs: 10_000 } });
  const cache = diskCache<{ category: string | null; reason: string }>('gates', MODEL, GATE_PROMPT_VERSION);
  type Row = Item & { rules: string | null; classifier: string | null; reason: string; combined: string | null };
  const rows: Row[] = [];
  for (const [n, item] of set.items.entries()) {
    let cls = cache.get(item.text);
    if (!cls) {
      cls = await withRetry(MODEL, () => classifierGate(client, MODEL, item.text));
      cache.set(item.text, cls);
    }
    const rules = ruleGate(item.text).category;
    rows.push({ ...item, rules, classifier: cls.category, reason: cls.reason, combined: rules ?? cls.category });
    process.stdout.write(`  ${n + 1}/${set.items.length}\r`);
  }
  process.stdout.write('\n');

  const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
  const stat = (subset: typeof rows, key: 'rules' | 'classifier' | 'combined') => {
    const gatedSet = subset.filter((r) => r.category !== 'none');
    const lookalikes = subset.filter((r) => r.category === 'none');
    const caught = gatedSet.filter((r) => r[key]).length;
    const wrong = lookalikes.filter((r) => r[key]).length;
    return { caught, of: gatedSet.length, wrong, ofLook: lookalikes.length, recall: caught / (gatedSet.length || 1), fp: wrong / (lookalikes.length || 1) };
  };
  const date = new Date().toISOString().slice(0, 10);
  const lines = [
    `# Pricing and legal gates, ${date}`,
    '',
    `Gate set ${set.version} (synthetic, unreviewed). Classifier ${MODEL}, prompt ${GATE_PROMPT_VERSION}. Generated by \`npm run eval:gates\`.`,
    '',
    `Bars agreed for Sprint 2: every pricing and legal question gated; at most ${pct(BARS.falsePositive)} of lookalikes gated. The app gates if either check fires ("combined").`,
    '',
    '| Split | Check | Pricing and legal gated | Lookalikes wrongly gated | Meets bars |',
    '|---|---|---|---|---|',
  ];
  for (const split of ['tuning', 'holdout', 'all']) {
    const subset = rows.filter((r) => split === 'all' || r.split === split);
    for (const key of ['rules', 'classifier', 'combined'] as const) {
      const s = stat(subset, key);
      lines.push(`| ${split} | ${key} | ${s.caught} of ${s.of} (${pct(s.recall)}) | ${s.wrong} of ${s.ofLook} (${pct(s.fp)}) | ${key === 'combined' ? (s.recall >= BARS.recall && s.fp <= BARS.falsePositive ? 'yes' : 'no') : ''} |`);
    }
  }
  for (const lang of ['en', 'ja']) {
    const s = stat(rows.filter((r) => r.language === lang), 'combined');
    lines.push(`| all, ${lang} | combined | ${s.caught} of ${s.of} | ${s.wrong} of ${s.ofLook} | |`);
  }
  const missed = rows.filter((r) => r.category !== 'none' && !r.combined);
  const wrongly = rows.filter((r) => r.category === 'none' && r.combined);
  const mislabelled = rows.filter((r) => r.category !== 'none' && r.combined && r.combined !== r.category);
  lines.push('', '## Missed (must be zero)', '', ...(missed.length ? missed.map((r) => `- ${r.id} (${r.category}): ${r.text}`) : ['None.']));
  lines.push('', '## Lookalikes wrongly gated', '', ...(wrongly.length ? wrongly.map((r) => `- ${r.id}: ${r.text} (rules: ${r.rules ?? 'no'}; classifier: ${r.classifier ?? 'no'}: ${r.reason})`) : ['None.']));
  lines.push('', `Gated under the other category (still gated, so still safe): ${mislabelled.length}.`, '');

  mkdirSync(join(ROOT, 'docs/evals'), { recursive: true });
  writeFileSync(join(ROOT, `docs/evals/gates-${date}.md`), lines.join('\n'));
  console.log(lines.join('\n'));
  console.log(`Written: docs/evals/gates-${date}.md`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
