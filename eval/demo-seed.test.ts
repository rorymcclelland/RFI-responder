// Sprint 7, S7-5: the demo seed generator. Test numbers refer to docs/refinement/sprint-7.md.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { checkPlan, demoSeedSql, kbSeedSql, lit, partlyHolds, replaceSection, type DemoPlan, type DemoRecording } from './demo-seed';

const plan = JSON.parse(readFileSync(new URL('../sample-data/demo-plan.json', import.meta.url), 'utf8')) as DemoPlan;

describe('S7-5 the demo plan', () => {
  it('2. the committed plan is fictional and well formed', () => {
    expect(checkPlan(plan)).toEqual([]);
    expect(plan.responses.map((r) => r.stage)).toEqual(['new', 'in_review', 'exported', 'archived']);
  });
  it('refuses a real-looking company, a real address, a bad ref or a dangling reference', () => {
    const bad: DemoPlan = { ...plan, responses: [{ ...plan.responses[1], name: 'Bluefin Freight: questionnaire', owner: 'someone@gmail.com',
      questions: [{ ref: '<A1>', text: 'q' }], assign: [{ ref: 'Z9', to: 'x@example.com', status: 'pending' }] }] };
    expect(checkPlan(bad).join('\n')).toMatch(/fictional[\s\S]*gmail[\s\S]*<A1>[\s\S]*Z9/);
  });
});

describe('S7-5 SQL generation', () => {
  it('quotes text safely', () => {
    expect(lit("O'Brien; DROP TABLE x")).toBe("'O''Brien; DROP TABLE x'");
    expect(lit(null)).toBe('NULL');
  });
  it('refuses text that could end a dollar-quoted block, and numbers that are not numbers (security review, Sprint 7)', () => {
    expect(() => lit('fine $kb$ SELECT 1; DO $x$')).toThrow(/dollar/);
    expect(() => lit('ends $demo$ early')).toThrow(/dollar/);
    expect(() => lit('$$')).toThrow(/dollar/);
    expect(lit('Costs $5 a month')).toBe("'Costs $5 a month'");
    const bad = { ...plan, responses: [{ ...plan.responses[1], dueDays: '1; DROP TABLE x' as unknown as number, bulkAt: 2 }] };
    expect(checkPlan(bad).join('\n')).toMatch(/dueDays[\s\S]*bulkAt/);
  });
  it('4. states its provenance, or seeds only the new response when there is no recording', () => {
    const none = demoSeedSql(plan, null);
    expect(none).toMatch(/No recording yet/);
    expect(none).toContain('Juniper Utilities (fictional)');
    expect(none).not.toContain('Bluefin');
  });
  it('refuses a recording that does not match the plan', () => {
    expect(() => demoSeedSql(plan, { recordedAt: '2026-10-24T00:00:00Z', planVersion: plan.version, models: {}, promptVersions: {}, results: {} }))
      .toThrow(/bluefin: the recording has 0 results for 14 questions/);
  });
  it('keeps the knowledge base in file order', () => {
    const sql = kbSeedSql([{ question: 'A?', answer: "It's fine.", tags: ['x'], source: 'P' }, { question: 'B?', answer: 'B.', tags: [], source: 'P' }]);
    expect(sql).toMatch(/\(1, 'A\?', 'It''s fine\.', ARRAY\['x'\]::text\[\], 'P'\),\n\s+\(2, 'B\?'/);
    expect(sql).toContain('ORDER BY v.ord');
  });
  it('replaces only the marked section', () => {
    const file = 'top\n-- BEGIN DEMO (generated by npm run demo:seed; do not edit by hand)\nold\n-- END DEMO\nbottom';
    expect(replaceSection(file, 'DEMO', 'new')).toBe('top\n-- BEGIN DEMO (generated by npm run demo:seed; do not edit by hand)\nnew\n-- END DEMO\nbottom');
    expect(() => replaceSection('nothing', 'DEMO', 'x')).toThrow(/no "DEMO" section/);
  });
});

// Sprint 8, S8-4. Test numbers refer to docs/refinement/sprint-8.md.
describe('S8-4 the demo shows the "partly" hold, and its usage is complete (F-37, F-38)', () => {
  const base = { id: 'x', generated_answer: 'Drafted.', confidence: 0.85, retrieval_score: 0.6, sources_json: [], answerability: 2.6, verdict: 'yes',
    gate: null, gate_reason: null, language: 'en', embedding_model: 'voyage-4', judge_model: 'claude-haiku-5-5', judge_best_ref: null, judge_reason: null,
    draft_model: 'claude-haiku-5-5', prompt_version: 'p', calibration_set: 's', draft_kind: 'generated', cited_refs: [], processing_note: null, processed_at: 't' } as const;
  const bluefin = plan.responses.find((r) => r.key === 'bluefin')!;
  const rec = (over: Record<string, object>) => ({ recordedAt: 't', planVersion: plan.version, models: {}, promptVersions: {},
    results: { bluefin: bluefin.questions.map((q) => ({ ...base, id: `bluefin-${q.ref}`, ...(over[q.ref] ?? {}) })) } }) as unknown as DemoRecording;

  it('finds drafted, ungated questions at the bulk line that the checker said only "partly" (or "no") answer', () => {
    const r = rec({ A13: { verdict: 'partly', confidence: 0.853 }, A14: { verdict: 'partly', confidence: 0.6 }, A5: { verdict: 'partly', confidence: 0.9, gate: 'legal' }, A6: { verdict: 'no', confidence: 0.81 } });
    expect(partlyHolds(plan, r).bluefin).toEqual(['A6', 'A13']);
    expect(partlyHolds(plan, rec({})).bluefin).toEqual([]);
  });

  it('3. the committed recording has one, or says to record again', () => {
    const real = JSON.parse(readFileSync(new URL('../supabase/demo-recording.json', import.meta.url), 'utf8')) as DemoRecording;
    expect(partlyHolds(plan, real).bluefin.length, 'The recorded demo has no question held for a "partly" verdict at 80%: run npm run demo:record again (the checker varies).').toBeGreaterThan(0);
  });

  it('2. writes embedding calls as the voyage provider and Claude calls as anthropic', () => {
    const one = plan.responses.find((r) => r.key === 'harbour')!;
    const results = one.questions.map((q) => ({ ...base, id: `harbour-${q.ref}` }));
    const sql = demoSeedSql({ ...plan, responses: [one] }, { recordedAt: '2026-10-25T00:00:00Z', planVersion: plan.version, models: {}, promptVersions: {},
      results: { harbour: results }, usage: { harbour: [{ kind: 'embed', model: 'voyage-4', inputTokens: 90, outputTokens: 0 }, { kind: 'judge', model: 'claude-haiku-5-5', inputTokens: 900, outputTokens: 50 }] } } as unknown as DemoRecording);
    expect(sql).toContain(`(owner, 'process-questions', 'embed', 'voyage', 'voyage-4', 90, 0, sess,`);
    expect(sql).toContain(`(owner, 'process-questions', 'judge', 'anthropic', 'claude-haiku-5-5', 900, 50, sess,`);
  });
});
