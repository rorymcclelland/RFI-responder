// Sprint 7, S7-5: the demo seed generator. Test numbers refer to docs/refinement/sprint-7.md.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { checkPlan, demoSeedSql, kbSeedSql, lit, replaceSection, type DemoPlan } from './demo-seed';

const plan = JSON.parse(readFileSync(new URL('../sample-data/demo-plan.json', import.meta.url), 'utf8')) as DemoPlan;

describe('S7-5 the demo plan', () => {
  it('2. the committed plan is fictional and well formed', () => {
    expect(checkPlan(plan)).toEqual([]);
    expect(plan.responses.map((r) => r.stage)).toEqual(['new', 'in_review', 'exported', 'archived']);
  });
  it('refuses a real-looking company, a real address, a bad ref or a dangling reference', () => {
    const bad: DemoPlan = { ...plan, responses: [{ ...plan.responses[1], name: 'Bluefin Freight: questionnaire', owner: 'someone@gmail.com',
      questions: [{ ref: '<A1>', text: 'q' }], assign: [{ ref: 'Z9', to: 'x@example.com', status: 'pending' }] }] };
    expect(checkPlan(bad).join('\n')).toMatch(/fictional[\s\S]*gmail[\s\S]*<A1>[\s\S]*Z9/);
  });
});

describe('S7-5 SQL generation', () => {
  it('quotes text safely', () => {
    expect(lit("O'Brien; DROP TABLE x")).toBe("'O''Brien; DROP TABLE x'");
    expect(lit(null)).toBe('NULL');
  });
  it('4. states its provenance, or seeds only the new response when there is no recording', () => {
    const none = demoSeedSql(plan, null);
    expect(none).toMatch(/No recording yet/);
    expect(none).toContain('Juniper Utilities (fictional)');
    expect(none).not.toContain('Bluefin');
  });
  it('refuses a recording that does not match the plan', () => {
    expect(() => demoSeedSql(plan, { recordedAt: '2026-10-24T00:00:00Z', planVersion: plan.version, models: {}, promptVersions: {}, results: {} }))
      .toThrow(/bluefin: the recording has 0 results for 12 questions/);
  });
  it('keeps the knowledge base in file order', () => {
    const sql = kbSeedSql([{ question: 'A?', answer: "It's fine.", tags: ['x'], source: 'P' }, { question: 'B?', answer: 'B.', tags: [], source: 'P' }]);
    expect(sql).toMatch(/\(1, 'A\?', 'It''s fine\.', ARRAY\['x'\]::text\[\], 'P'\),\n\s+\(2, 'B\?'/);
    expect(sql).toContain('ORDER BY v.ord');
  });
  it('replaces only the marked section', () => {
    const file = 'top\n-- BEGIN DEMO (generated by npm run demo:seed; do not edit by hand)\nold\n-- END DEMO\nbottom';
    expect(replaceSection(file, 'DEMO', 'new')).toBe('top\n-- BEGIN DEMO (generated by npm run demo:seed; do not edit by hand)\nnew\n-- END DEMO\nbottom');
    expect(() => replaceSection('nothing', 'DEMO', 'x')).toThrow(/no "DEMO" section/);
  });
});
