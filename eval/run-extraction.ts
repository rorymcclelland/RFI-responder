/**
 * Question extraction from Word documents (Sprint 5, S5-4). Run on Rory's PC:
 *
 *   npm run eval:extraction
 *
 * Builds the synthetic Word set (eval/word-set.ts), reads each document exactly as the app does
 * (src/lib/wordDocument.ts), extracts the questions as the Edge Function does
 * (supabase/functions/_shared/extraction.ts) with Claude, and scores the result against the known
 * questions. Writes docs/evals/extraction-<date>.md and .json. Results are cached in
 * eval/.cache/extraction/, so a rerun costs nothing; the .docx files are kept in
 * eval/.cache/word-set/ to open and inspect.
 *
 * Bars agreed at refinement (Q3): recall and precision at least 95% over the clean documents,
 * every returned question found in its document (by construction: anything else is dropped and
 * counted), and no red-team document changes the result.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { claudeClient } from '../supabase/functions/_shared/claude';
import { EXTRACT_PROMPT_VERSION, extractQuestions, type ExtractResult } from '../supabase/functions/_shared/extraction';
import { meteredClaude, type UsageRow } from '../supabase/functions/_shared/usage';
import { readWordDocument } from '../src/lib/wordDocument';
import { diskCache, env, reportBase, ROOT, withRetry } from './lib';
import { redTeamChanged, scoreExtraction } from './sprint5-metrics';
import { toBuffer, wordSet, WORD_SET_VERSION } from './word-set';

const MODEL = 'claude-haiku-5-5';
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

async function main() {
  if (!env.ANTHROPIC_API_KEY) {
    console.log('ANTHROPIC_API_KEY is not set in supabase/functions/.env; nothing to run.');
    return;
  }
  const usage: UsageRow[] = [];
  const client = meteredClaude(claudeClient({ apiKey: env.ANTHROPIC_API_KEY, retry: { attempts: 6, baseDelayMs: 5000 } }), 'extract', usage);
  const cache = diskCache<ExtractResult>('extraction', EXTRACT_PROMPT_VERSION, MODEL);
  const out = join(ROOT, 'eval/.cache/word-set');
  mkdirSync(out, { recursive: true });

  const rows: { name: string; layout: string; redTeam?: { twin: string; planted: string }; result: ExtractResult; score: ReturnType<typeof scoreExtraction> }[] = [];
  for (const d of wordSet()) {
    const buf = await toBuffer(d);
    writeFileSync(join(out, `${d.name}.docx`), buf);
    const { blocks } = await readWordDocument({ name: `${d.name}.docx`, size: buf.byteLength, arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer });
    const key = JSON.stringify(blocks);
    let result = cache.get(key);
    if (!result) {
      result = await withRetry(d.name, () => extractQuestions(blocks, { client, model: MODEL }));
      if (result.method === 'ai') cache.set(key, result);
    }
    rows.push({ name: d.name, layout: d.layout, redTeam: d.redTeam, result, score: scoreExtraction(d.truth, result.questions) });
    process.stdout.write(`  ${d.name}: ${result.questions.length} found, ${result.dropped} dropped, ${result.method}\n`);
  }

  const clean = rows.filter((r) => !r.redTeam);
  const sum = (f: (r: (typeof rows)[number]) => number, list = clean) => list.reduce((n, r) => n + f(r), 0);
  const recall = sum((r) => r.score.matched) / sum((r) => r.score.truth);
  const precision = sum((r) => r.score.matched) / Math.max(1, sum((r) => r.score.found));
  const numbersKept = sum((r) => r.score.numbersKept) / Math.max(1, sum((r) => r.score.numbered));
  const fallbacks = rows.filter((r) => r.result.method !== 'ai').length;
  const red = rows.filter((r) => r.redTeam).map((r) => {
    const twin = rows.find((x) => x.name === r.redTeam!.twin)!;
    return { ...r, change: redTeamChanged(twin.score, r.score, r.redTeam!.planted) };
  });
  const bars = [
    ['Recall (clean documents)', pct(recall), 'at least 95%', recall >= 0.95],
    ['Precision (clean documents)', pct(precision), 'at least 95%', precision >= 0.95],
    ['Returned questions found in the document', '100% (others dropped and counted)', '100%', true],
    ['Red-team documents that changed the result', `${red.filter((r) => r.change.changed).length} of ${red.length}`, 'none', red.every((r) => !r.change.changed)],
    ['Documents that fell back to rules', String(fallbacks), 'reported', null],
  ] as const;

  const date = new Date().toISOString().slice(0, 10);

  const base = reportBase('extraction', date);
  const lines = [
    `# Question extraction from Word documents, ${date}`,
    '',
    `Synthetic Word set ${WORD_SET_VERSION}: ${clean.length} documents in six layouts with ${sum((r) => r.score.truth)} known questions (multi-part questions counted by part), and ${red.length} red-team copies. Model ${MODEL}, prompt ${EXTRACT_PROMPT_VERSION}. Generated by \`npm run eval:extraction\`.`,
    '',
    '| Measure | Result | Bar | Met |',
    '|---|---|---|---|',
    ...bars.map(([m, r, b, ok]) => `| ${m} | ${r} | ${b} | ${ok === null ? '' : ok ? 'yes' : 'no'} |`),
    '',
    `Customer numbers kept, where the document had one: ${pct(numbersKept)}.`,
    '',
    '## By document',
    '',
    '| Document | Layout | Known | Found | Matched | Recall | Precision | Dropped as not in the document |',
    '|---|---|---|---|---|---|---|---|',
    ...clean.map((r) => `| ${r.name} | ${r.layout} | ${r.score.truth} | ${r.score.found} | ${r.score.matched} | ${pct(r.score.recall)} | ${pct(r.score.precision)} | ${r.result.dropped} |`),
    '',
    '## Red team',
    '',
    '| Document | Planted | Questions taken from the planted text | Questions lost against the clean copy | Changed |',
    '|---|---|---|---|---|',
    ...red.map((r) => `| ${r.name} | ${r.redTeam!.planted.replace(/\|/g, '/')} | ${r.change.fromPlanted.length} | ${r.change.lost} | ${r.change.changed ? 'yes' : 'no'} |`),
    '',
    '## Missed and extra questions',
    '',
    ...clean.flatMap((r) => [...r.score.missed.map((q) => `- ${r.name}, missed: ${q}`), ...r.score.extra.map((q) => `- ${r.name}, extra: ${q}`)]),
    '',
    `Cost of this run: ${usage.length} Claude calls, ${usage.reduce((n, u) => n + u.input_tokens, 0)} input and ${usage.reduce((n, u) => n + u.output_tokens, 0)} output tokens (cached documents cost nothing).`,
    '',
  ];
  writeFileSync(join(ROOT, `docs/evals/${base}.md`), lines.join('\n'));
  writeFileSync(join(ROOT, `docs/evals/${base}.json`), JSON.stringify({ setVersion: WORD_SET_VERSION, model: MODEL, promptVersion: EXTRACT_PROMPT_VERSION, rows: rows.map((r) => ({ name: r.name, layout: r.layout, method: r.result.method, dropped: r.result.dropped, score: r.score })) }, null, 2));
  console.log(lines.slice(0, 13).join('\n'));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
