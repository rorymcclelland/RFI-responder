/**
 * How much the answerability checker's verdict and the calibrated confidence move between runs
 * when nothing else changes (Sprint 5, F-22). Run on Rory's PC after `npm run eval:retrieval`:
 *
 *   npm run eval:consistency
 *   npm run eval:consistency -- --runs=3
 *
 * Asks the Claude judge about every test-split item of the evaluation set several times (five by
 * default), with the voyage-4 entries the app would draft from, and reports how often the verdict
 * changes, how far confidence moves, and how often a question crosses the 80% bulk line or the
 * no-draft floor between runs. Measurement only: any mitigation is decided at the sprint's close.
 * Each run's answers are cached in eval/.cache/consistency/, so an interrupted run resumes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { claudeJudge, type AnswerabilityResult } from '../supabase/functions/_shared/answerability';
import { calibratedConfidence, NO_MATCH_FLOOR } from '../supabase/functions/_shared/calibration';
import { CALIBRATION_TABLES } from '../supabase/functions/_shared/calibration-tables';
import { claudeClient } from '../supabase/functions/_shared/claude';
import { meteredClaude, type UsageRow } from '../supabase/functions/_shared/usage';
import { candidatesFor, vectorsFor } from './judge-inputs';
import { diskCache, env, hashKey, loadKb, ROOT, withRetry } from './lib';
import { consistency } from './sprint5-metrics';

interface Item { id: string; text: string; language: string; kind: string; split: string }
const MODEL = 'claude-haiku-5-5';
const METHOD = `voyage-4 + ${MODEL}`;
const RUNS = Number(process.argv.find((a) => a.startsWith('--runs='))?.slice(7) ?? 5);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

async function main() {
  if (!env.ANTHROPIC_API_KEY) {
    console.log('ANTHROPIC_API_KEY is not set in supabase/functions/.env; nothing to run.');
    return;
  }
  const vecs = vectorsFor('voyage/voyage-4');
  if (typeof vecs === 'string') {
    console.log(vecs);
    return;
  }
  const kb = loadKb();
  const set = JSON.parse(readFileSync(join(ROOT, 'eval/retrieval-set.json'), 'utf8')) as { version: string; items: Item[] };
  const items = set.items.filter((i) => i.split === 'test' && vecs.query[hashKey(i.text)]);
  const docVecs = kb.map((e) => vecs.doc[hashKey(`${e.question}\n${e.answer}`)]);
  const usage: UsageRow[] = [];
  const judge = claudeJudge({ client: meteredClaude(claudeClient({ apiKey: env.ANTHROPIC_API_KEY, retry: { attempts: 6, baseDelayMs: 5000 } }), 'judge', usage), model: MODEL });

  const per = new Map<string, { item: Item; runs: { verdict: string | null; confidence: number | null }[] }>();
  for (let run = 1; run <= RUNS; run++) {
    const cache = diskCache<AnswerabilityResult>('consistency', MODEL, `run-${run}`);
    for (const [n, item] of items.entries()) {
      const cands = candidatesFor(kb, docVecs, vecs.query[hashKey(item.text)]);
      const key = JSON.stringify([item.text, cands.map((c) => c.ref)]);
      let r = cache.get(key);
      if (!r) {
        r = await withRetry(`run ${run}`, () => judge.check(item.text, cands));
        cache.set(key, r);
      }
      const score = r.verdict ? { no: 0, partly: 1, yes: 2 }[r.verdict] + Math.max(0, Math.min(1, cands[0]?.similarity ?? 0)) : null;
      const confidence = score === null ? null : calibratedConfidence(score, METHOD, CALIBRATION_TABLES);
      const entry = per.get(item.id) ?? { item, runs: [] };
      entry.runs.push({ verdict: r.verdict ?? null, confidence });
      per.set(item.id, entry);
      process.stdout.write(`  run ${run}/${RUNS}: ${n + 1}/${items.length}\r`);
    }
    process.stdout.write('\n');
  }

  const results = [...per.values()].map((p) => ({ ...p, c: consistency(p.runs, 0.8, NO_MATCH_FLOOR) }));
  const share = (f: (r: (typeof results)[number]) => boolean, list = results) => (list.length ? list.filter(f).length / list.length : 0);
  const kinds = [...new Set(results.map((r) => r.item.kind))];
  const date = new Date().toISOString().slice(0, 10);
  const lines = [
    `# Checker consistency across runs, ${date}`,
    '',
    `Evaluation set ${set.version}, test split (${results.length} questions; synthetic, unreviewed). ${RUNS} runs of the ${MODEL} judge with the voyage-4 entries the app would draft from; confidence calibrated with the current tables (${METHOD}). Generated by \`npm run eval:consistency\`. Measurement only (F-22): any mitigation is decided at the Sprint 5 close.`,
    '',
    '| Measure | All | ' + kinds.join(' | ') + ' |',
    '|---|---|' + kinds.map(() => '---|').join(''),
    `| Verdict changed between runs | ${pct(share((r) => r.c.flipped))} | ${kinds.map((k) => pct(share((r) => r.c.flipped, results.filter((r) => r.item.kind === k)))).join(' | ')} |`,
    `| Crossed the 80% bulk line | ${pct(share((r) => r.c.crossesBulkLine))} | ${kinds.map((k) => pct(share((r) => r.c.crossesBulkLine, results.filter((r) => r.item.kind === k)))).join(' | ')} |`,
    `| Crossed the no-draft floor (${NO_MATCH_FLOOR * 100}%) | ${pct(share((r) => r.c.crossesFloor))} | ${kinds.map((k) => pct(share((r) => r.c.crossesFloor, results.filter((r) => r.item.kind === k)))).join(' | ')} |`,
    `| Mean confidence spread (highest minus lowest) | ${(results.reduce((n, r) => n + r.c.spread, 0) / Math.max(1, results.length) * 100).toFixed(1)} points | ${kinds.map((k) => { const l = results.filter((r) => r.item.kind === k); return `${(l.reduce((n, r) => n + r.c.spread, 0) / Math.max(1, l.length) * 100).toFixed(1)} points`; }).join(' | ')} |`,
    '',
    '## Questions whose verdict changed',
    '',
    ...results.filter((r) => r.c.flipped).map((r) => `- ${r.item.id} (${r.item.kind}): ${r.runs.map((x) => `${x.verdict ?? 'none'} ${x.confidence === null ? '' : pct(x.confidence)}`).join(', ')}`),
    '',
    `Cost of this run: ${usage.length} new Claude calls, ${usage.reduce((n, u) => n + u.input_tokens, 0)} input and ${usage.reduce((n, u) => n + u.output_tokens, 0)} output tokens (cached answers cost nothing).`,
    '',
  ];
  writeFileSync(join(ROOT, `docs/evals/consistency-${date}.md`), lines.join('\n'));
  console.log(lines.slice(0, 10).join('\n'));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
