/**
 * Calibration for Sprint 1 (story S1-6). Run after `npm run eval:retrieval`:
 *
 *   npm run eval:calibrate
 *
 * For each embedding model in the newest docs/evals/retrieval-*.json, fits an
 * isotonic curve from the top match's cosine similarity to whether the top entry was
 * right, on the `calibrate` split (unanswerable questions count as wrong), then checks
 * it on the `test` split against the agreed bars. Writes src/lib/calibration/<model>.json
 * (used by the app) and docs/evals/calibration-<date>.md.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { calibratedConfidence, NO_MATCH_FLOOR, type CalibrationTable } from '../src/lib/calibration';
import { expectedCalibrationError, isotonicFit, reliabilityBins, toBreakpoints } from './calibration-fit';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BARS = { ece: 0.1, abstention: 0.8 };

interface ItemResult { id: string; kind: string; split: string; method: string; topScore: number; topIsGold: boolean }

const reports = readdirSync(join(ROOT, 'docs/evals')).filter((f) => /^retrieval-.*\.json$/.test(f)).sort();
if (reports.length === 0) {
  console.error('No docs/evals/retrieval-*.json found. Run `npm run eval:retrieval` first.');
  process.exit(1);
}
const latest = reports[reports.length - 1];
const data = JSON.parse(readFileSync(join(ROOT, 'docs/evals', latest), 'utf8')) as {
  setVersion: string; results: ItemResult[];
};

// Vector-only methods: the app calibrates on the top cosine similarity.
const models = [...new Set(data.results.map((r) => r.method))].filter((m) => !m.includes('keyword'));
const date = new Date().toISOString().slice(0, 10);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const lines: string[] = [
  `# Calibration, ${date}`,
  '',
  `From \`${latest}\` (evaluation set ${data.setVersion}; all items unreviewed, Japanese machine-translated). Fitted on the \`calibrate\` split, checked on the \`test\` split. Generated by \`npm run eval:calibrate\`.`,
  '',
  `Bars agreed for Sprint 1: expected calibration error at most ${BARS.ece}; at least ${pct(BARS.abstention)} of unanswerable questions below the no-match floor (${NO_MATCH_FLOOR}).`,
  '',
  '| Model | Calibration error (test) | Unanswerable below floor (test) | Answerable below floor (test) | Meets bars |',
  '|---|---|---|---|---|',
];
const details: string[] = [];

mkdirSync(join(ROOT, 'src/lib/calibration'), { recursive: true });
for (const model of models) {
  const rows = data.results.filter((r) => r.method === model);
  const fitRows = rows.filter((r) => r.split === 'calibrate');
  const testRows = rows.filter((r) => r.split === 'test');
  const table: CalibrationTable = {
    model,
    evaluationSet: `${data.setVersion} (calibrate split)`,
    points: toBreakpoints(isotonicFit(fitRows.map((r) => ({ x: r.topScore, y: r.topIsGold ? 1 : 0 })))),
  };
  const tables = { [model]: table };
  const predictions = testRows.map((r) => ({
    p: calibratedConfidence(r.topScore, model, tables) ?? 0, correct: r.topIsGold, kind: r.kind,
  }));
  const ece = expectedCalibrationError(predictions);
  const unans = predictions.filter((p) => p.kind === 'unanswerable');
  const ans = predictions.filter((p) => p.kind !== 'unanswerable');
  const unansBelow = unans.filter((p) => p.p < NO_MATCH_FLOOR).length / (unans.length || 1);
  const ansBelow = ans.filter((p) => p.p < NO_MATCH_FLOOR).length / (ans.length || 1);
  const meets = ece <= BARS.ece && unansBelow >= BARS.abstention;
  lines.push(`| ${model} | ${ece.toFixed(3)} | ${pct(unansBelow)} | ${pct(ansBelow)} | ${meets ? 'yes' : 'no'} |`);

  writeFileSync(join(ROOT, `src/lib/calibration/${model.replace(/[^a-z0-9.-]/gi, '_')}.json`), JSON.stringify(table, null, 2) + '\n');
  details.push(
    '', `## ${model}: reliability on the test split`, '',
    '| Predicted | Questions | Mean predicted | Observed right |', '|---|---|---|---|',
    ...reliabilityBins(predictions).filter((b) => b.count > 0)
      .map((b) => `| ${b.range} | ${b.count} | ${pct(b.meanPredicted)} | ${pct(b.observed)} |`),
  );
}

lines.push('', '"Answerable below floor" is the cost of the floor: answerable questions sent to a person although the knowledge base had the answer.', ...details, '');
writeFileSync(join(ROOT, `docs/evals/calibration-${date}.md`), lines.join('\n'));
console.log(lines.join('\n'));
console.log(`\nWritten: docs/evals/calibration-${date}.md and src/lib/calibration/*.json`);
