/**
 * Near-duplicate threshold for learning at export (Sprint 3, story S3-4b).
 *
 *   npm run eval:duplicates
 *
 * When an edited answer is learned, it supersedes its top-matched entry if that entry is a
 * near-duplicate: similarity at or above a threshold, and the judge said the entry answers the
 * question (yes or partly). A wrong supersession replaces a different question's entry, which
 * loses knowledge, so the threshold is the lowest at which wrong supersessions stay at or below
 * 2% of all questions. Uses the committed retrieval and answerability reports (no API calls):
 * each paraphrase and translation has a known right entry; unanswerable questions have none.
 * Writes docs/evals/duplicates-<date>.md and supabase/functions/_shared/duplicate-thresholds.json.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib';

const MAX_WRONG = 0.02;
interface Row { id: string; kind: string; language: string; method: string; topIsGold: boolean; verdict: string | null; similarity: number; unreadable?: boolean }

const latest = (kind: string) => readdirSync(join(ROOT, 'docs/evals')).filter((f) => new RegExp(`^${kind}-.*\\.json$`).test(f)).sort().pop()!;
const file = latest('answerability');
const data = JSON.parse(readFileSync(join(ROOT, 'docs/evals', file), 'utf8')) as { setVersion: string; results: Row[] };

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const date = new Date().toISOString().slice(0, 10);
const lines = [
  `# Near-duplicate threshold, ${date}`,
  '',
  `From \`${file}\` (evaluation set ${data.setVersion}; synthetic, unreviewed). A learned answer supersedes its top entry when the similarity is at or above the threshold and the judge said "yes" or "partly". Bar: wrong supersessions (top entry is not the question's own, or the question has none) at most ${pct(MAX_WRONG)} of all questions. Generated by \`npm run eval:duplicates\`.`,
  '',
  '| Embedding | Threshold | Wrong supersessions | Real duplicates caught | Without the judge condition: wrong, caught |',
  '|---|---|---|---|---|',
];
const thresholds: Record<string, number> = {};

for (const method of [...new Set(data.results.map((r) => r.method))]) {
  // An unreadable check never supersedes in the app (no verdict); left out rather than counted (Sprint 6 review).
  const rows = data.results.filter((r) => r.method === method && !r.unreadable);
  const embedding = method.split(' + ')[0];
  const answerable = rows.filter((r) => r.kind === 'paraphrase' || r.kind === 'translation');
  const stats = (t: number, judge: boolean) => {
    const sup = (r: Row) => r.similarity >= t && (!judge || r.verdict === 'yes' || r.verdict === 'partly');
    return {
      wrong: rows.filter((r) => sup(r) && !r.topIsGold).length / rows.length,
      caught: answerable.filter((r) => sup(r) && r.topIsGold).length / answerable.length,
    };
  };
  let chosen = 1;
  for (let t = 0.3; t <= 0.95; t = Math.round((t + 0.01) * 100) / 100) {
    if (stats(t, true).wrong <= MAX_WRONG) {
      chosen = t;
      break;
    }
  }
  thresholds[embedding] = chosen;
  const withJudge = stats(chosen, true);
  const without = stats(chosen, false);
  lines.push(`| ${embedding} | ${chosen.toFixed(2)} | ${pct(withJudge.wrong)} | ${pct(withJudge.caught)} | ${pct(without.wrong)}, ${pct(without.caught)} |`);
}
lines.push('', 'A question whose similarity is below the threshold is learned as a new entry beside the existing ones, so a missed duplicate costs a duplicate entry, not lost knowledge.', '');

writeFileSync(join(ROOT, `docs/evals/duplicates-${date}.md`), lines.join('\n'));
writeFileSync(join(ROOT, 'supabase/functions/_shared/duplicate-thresholds.json'), JSON.stringify({ evaluationSet: data.setVersion, maxWrong: MAX_WRONG, thresholds }, null, 2) + '\n');
console.log(lines.join('\n'));
